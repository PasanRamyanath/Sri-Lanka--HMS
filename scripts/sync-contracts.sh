#!/usr/bin/env bash
# ==============================================================================
# sync-contracts.sh — Cross-Repo GraphQL Contract Synchronizer
# Sri Lanka Cloud SaaS Hotel Management System
#
# Generates TypeScript contracts from the backend GraphQL schema and synchronizes
# them into HMS-Frontend/src/generated/graphql.ts for complete end-to-end type safety.
# ==============================================================================

set -euo pipefail

ROOT_DIR="/workspaces/Sri-Lanka--HMS"
BACKEND_DIR="${ROOT_DIR}/HMS-Backend"
FRONTEND_DIR="${ROOT_DIR}/HMS-Frontend"
FRONTEND_GENERATED_DIR="${FRONTEND_DIR}/src/generated"
SOURCE_CONTRACTS="${BACKEND_DIR}/packages/graphql/src/generated/types.ts"
if [ ! -f "${SOURCE_CONTRACTS}" ]; then
  SOURCE_CONTRACTS="${BACKEND_DIR}/packages/graphql/src/generated/graphql.ts"
fi
TARGET_CONTRACTS="${FRONTEND_GENERATED_DIR}/graphql.ts"

mkdir -p "${FRONTEND_GENERATED_DIR}"

# Run codegen in HMS-Backend if codegen config exists
if [ -f "${BACKEND_DIR}/packages/graphql/codegen.ts" ]; then
  npm --prefix "${BACKEND_DIR}" run codegen || true
fi

# Synchronize generated contracts if present, or create placeholder contract
if [ -f "${SOURCE_CONTRACTS}" ]; then
  cp -f "${SOURCE_CONTRACTS}" "${TARGET_CONTRACTS}"
else
  # Provide initial typed contract placeholder until Phase 03 SDL codegen
  cat << 'EOF' > "${TARGET_CONTRACTS}"
/**
 * @hms/graphql - Synchronized Cross-Repo GraphQL Contracts.
 * Auto-generated by scripts/sync-contracts.sh from HMS-Backend.
 */

export type Maybe<T> = T | null;
export type Exact<T extends { [key: string]: unknown }> = { [K in keyof T]: T[K] };

export interface BaseEntity {
  id: string;
  tenantId: string;
  createdAt: string;
  updatedAt: string;
}
EOF
fi

chmod 644 "${TARGET_CONTRACTS}"
